'use strict';
// Package generated portraits and derive consistent face crops from the same
// artwork. This only crops/resizes finished pixels; it never draws a character.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require(process.env.CHARACTER_SHARP || 'C:/Users/ruofa/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root = path.resolve(__dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'scripts/character-restoration-spec.json'), 'utf8').replace(/^\uFEFF/, ''));
const staging = process.argv.includes('--stage');
const outputRoot = path.join(root, staging ? '.scratch/character-restored-runtime' : 'assets/characters');
const crops = {
  pyro: { avatar: [270, 10, 350, 360], cutin: [185, 0, 570, 570] },
  shadow: { avatar: [235, 12, 380, 375], cutin: [190, 0, 590, 590] },
  gale: { avatar: [245, 4, 360, 380], cutin: [185, 0, 580, 580] },
  bastion: { avatar: [145, 0, 405, 390], cutin: [90, 0, 610, 610] },
  iron: { avatar: [300, 4, 310, 330], cutin: [235, 0, 555, 555] },
};
const report = [];
async function main() {
  for (const p of spec.portraits) {
    const input = path.resolve(root, p.generatedImage), output = path.join(outputRoot, p.id);
    fs.mkdirSync(output, { recursive: true });
    await sharp(input).trim({ threshold: 2 }).png().toFile(path.join(output, 'portrait.png'));
    for (const [kind, rect] of Object.entries(crops[p.id])) {
      const [left, top, width, height] = rect;
      await sharp(input).extract({ left, top, width, height })
        .resize(kind === 'avatar' ? 384 : 768, kind === 'avatar' ? 384 : 768, {
          fit: 'contain', background: '#00000000', kernel: 'lanczos3',
        }).png().toFile(path.join(output, kind + '.png'));
    }
    const meta = await sharp(path.join(output, 'portrait.png')).metadata();
    report.push({ id: p.id, portraitSize: [meta.width, meta.height], avatarSize: [384,384], cutinSize: [768,768], source: p.generatedImage, crops: crops[p.id], instrumentSource: p.instrumentUrl, strings: p.strings });
    console.log(`Packed ${p.name}: ${meta.width}x${meta.height}, matching avatar and cut-in`);
  }
  fs.writeFileSync(path.join(root, '.scratch/character-restored-portrait-validation.json'), JSON.stringify(report, null, 2) + '\n');
  if (staging) return;
  const artPath = path.join(root, 'scripts/character-art-spec.json');
  const art = JSON.parse(fs.readFileSync(artPath, 'utf8'));
  const portraitPath = path.join(root, 'scripts/character-portrait-spec.json');
  const portraits = JSON.parse(fs.readFileSync(portraitPath, 'utf8'));
  const manifestPath = path.join(root, 'assets/characters/manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  for (const p of spec.portraits) {
    art.characters.find(c => c.id === p.id).portraitSourceImage = p.generatedImage;
    const old = portraits.characters.find(c => c.id === p.id), data = report.find(c => c.id === p.id);
    Object.assign(old, { previousGeneratorOutput: old.generatorOutput, generatorOutput: p.generatorOutput,
      subject: p.character, instrument: p.instrument, prompt: p.prompt, referenceImage: p.characterRef,
      instrumentReference: p.instrumentRef, officialReference: p.characterUrl, generatedImage: p.generatedImage,
      runtimeImage: `assets/characters/${p.id}/portrait.png`, repairPrompt: p.repairPrompt,
      avatarCrop: data.crops.avatar, cutinCrop: data.crops.cutin });
    Object.assign(manifest.characters[p.id], { portraitSize: data.portraitSize,
      instrument: { description: p.instrument, strings: p.strings, reference: p.instrumentUrl },
      faceCropSource: p.generatedImage });
  }
  manifest.version = (manifest.version || 7) + 1;
  fs.writeFileSync(artPath, JSON.stringify(art, null, 2) + '\n');
  fs.writeFileSync(portraitPath, JSON.stringify(portraits, null, 2) + '\n');
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'src/game/character-assets.ts'), '// Generated by scripts/prepare-restored-portraits.cjs\nimport type { CharacterAssetManifest } from \'./asset-types\';\nconst manifest: CharacterAssetManifest = ' + JSON.stringify(manifest, null, 2) + ';\nexport default manifest;\n');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
